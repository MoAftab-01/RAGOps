"""Demonstration RAG support bot (§12) — runnable end to end.

    cd evaluation && python -m rag_demo.app --query "How do I reset my password?"

This exercises the same pipeline the HTTP API does, with the same modules and
the same configuration, but prints what each stage retrieved instead of
returning a trace id. The point is that every number printed here is measured
by the run in front of you: BM25 scores, cosine similarities, rerank scores,
token counts and timings are all real, and the answer is generated by the local
Ollama model rather than written into the file.

What the script deliberately does **not** do:

* it does not print a "quality score". Retrieval quality is a property of a
  labelled dataset, not of a single unlabelled question, so guessing one here
  would be exactly the fabrication §35 forbids. Run
  ``POST /api/evaluations/retrieval`` (or ``make`` the evaluation script) for
  Precision@K and friends against ``retrieval_eval.jsonl``.
* it does not report a cost saving or an optimal configuration. One query
  cannot support either claim.
* it does not silently fall back to a canned answer. If Ollama is not running,
  the generation stage fails loudly and the retrieval results are still shown —
  because retrieval working and generation being unavailable are two different
  facts, and collapsing them into one "it didn't work" loses the first.

Every stage is timed separately, so a slow run can be attributed rather than
guessed at.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import sys
from pathlib import Path
from typing import Any

# Run from `evaluation/`, so the backend package is one level up and is not
# importable by default. Done before importing anything from `app`.
_BACKEND = Path(__file__).resolve().parents[2] / "backend"
if str(_BACKEND) not in sys.path:
    sys.path.insert(0, str(_BACKEND))

from app.config import settings  # noqa: E402
from app.ml.retriever import get_retrieval_service  # noqa: E402
from app.providers.registry import get_provider  # noqa: E402
from app.utils.tokens import estimate_tokens  # noqa: E402

_QUESTION = "How do I reset my password?"


def _rule(title: str) -> None:
    print(f"\n{title}\n{'-' * len(title)}")


def _show(value: object) -> str:
    """A score for printing: full precision, or an explicit 'not run'."""
    return "not run" if value is None else f"{float(value):.4f}"


def _show_retrieval(service: Any, query: str, top_k: int) -> list[Any]:
    """Run retrieval and print each stage's own contribution.

    The three scores are shown side by side on purpose. They are not
    comparable to each other — BM25 is unbounded and corpus-relative, cosine is
    in [-1, 1], and the cross-encoder score is neither — which is exactly why
    fusion is done on *ranks* rather than on these numbers.
    """
    result = service.query(query, top_k=top_k)

    _rule("Retrieval")
    print(f"query            : {query!r}")
    print(f"chunks indexed   : {service.num_chunks}")
    print(f"knowledge base   : {service.knowledge_base_path}")
    print(f"hits returned    : {len(result.results)}")

    config = service.configuration()
    print(
        "config           : "
        f"top_k={config.get('top_k')} "
        f"rerank={'on' if config.get('rerank_enabled') else 'off'} "
        f"rrf_k={config.get('rrf_k')}"
    )

    _rule("Retrieved chunks")
    for hit in result.results:
        print(f"\n[{hit.rank}] {hit.title}")
        print(f"    source    : {hit.source}")
        print(f"    chunk id  : {hit.document_id}")
        # None here means the stage did not run for this hit, which is
        # different from a stage that ran and scored zero.
        print(f"    bm25      : {_show(hit.bm25_score)}")
        print(f"    vector    : {_show(hit.vector_score)}")
        print(f"    rerank    : {_show(hit.rerank_score)}")
        print(f"    fused     : {_show(hit.final_score)}")
        print(f"    tokens    : {hit.context_tokens}")
        preview = hit.content.strip().replace("\n", " ")
        print(f"    text      : {preview[:220]}{'...' if len(preview) > 220 else ''}")

    _rule("Retrieval timings (ms)")
    for stage, value in result.timings_ms.items():
        print(f"  {stage:<20} {value:>10.3f}")

    return result.results


async def _generate(query: str, hits: list[Any]) -> tuple[str, Any]:
    """Generate an answer from the retrieved context via local Ollama."""
    provider = get_provider("ollama")

    if not await provider.available():
        raise RuntimeError(
            f"Ollama is not reachable at {settings.ollama_base_url}.\n"
            f"  Start it with:  ollama serve\n"
            f"  Then pull it with:  ollama pull {settings.ollama_model}"
        )

    if not hits:
        # An empty context block would let the model answer from its own
        # weights, which looks like a working bot and is the exact failure
        # this platform exists to make visible. Refuse instead.
        return (
            "No documents were retrieved for this question, so there is nothing "
            "to answer from. The knowledge base does not cover it.",
            None,
        )

    context = "\n\n".join(
        f"[{index}] {hit.title} ({hit.source or 'unknown source'})\n{hit.content}"
        for index, hit in enumerate(hits, start=1)
    )
    prompt = (
        "Answer the question using only the context below. If the context does "
        "not contain the answer, say so. Cite the sources you used as [1], [2].\n\n"
        f"Context:\n{context}\n\nQuestion: {query}"
    )

    response = await provider.generate([{"role": "user", "content": prompt}])
    return response.text, response


def _show_answer(answer: str, response: Any | None, hits: list[Any]) -> None:
    _rule("Answer")
    print(answer.strip() or "(the model returned an empty answer)")

    if response is None:
        return

    _rule("Generation")
    print(f"  model           : {response.model}")
    print(f"  latency         : {response.latency_ms:.1f} ms")
    print(f"  input tokens    : {response.input_tokens}")
    print(f"  output tokens   : {response.output_tokens}")
    print(f"  total tokens    : {response.total_tokens}")
    print(f"  context tokens  : {estimate_tokens(' '.join(h.content for h in hits))}")
    # Whether the provider counted these itself or fell back to the documented
    # heuristic. Presenting an estimate as an engine measurement is the kind of
    # small dishonesty that makes every downstream average untrustworthy.
    exactness = "exact (counted by the engine)" if response.token_counts_exact else "estimated (heuristic)"
    print(f"  count source    : {exactness}")


async def _run(query: str, top_k: int, as_json: bool) -> int:
    service = get_retrieval_service()
    hits = _show_retrieval(service, query, top_k)

    try:
        answer, response = await _generate(query, hits)
    except RuntimeError as exc:
        # Retrieval still worked, and saying so is more useful than a stack
        # trace: the operator needs to know which of the two halves is broken.
        print(f"\nGeneration unavailable:\n{exc}", file=sys.stderr)
        print(
            "\nRetrieval above completed normally — the failure is in the LLM "
            "provider, not the index.",
            file=sys.stderr,
        )
        return 1

    if as_json:
        print(json.dumps(
            {
                "query": query,
                "hits": [
                    {
                        "document_id": hit.document_id,
                        "source": hit.source,
                        "title": hit.title,
                        "rank": hit.rank,
                        "bm25_score": hit.bm25_score,
                        "vector_score": hit.vector_score,
                        "rerank_score": hit.rerank_score,
                        "final_score": hit.final_score,
                        "token_count": hit.context_tokens,
                    }
                    for hit in hits
                ],
                "answer": answer,
                "model": getattr(response, "model", None),
                "input_tokens": getattr(response, "input_tokens", None),
                "output_tokens": getattr(response, "output_tokens", None),
                "latency_ms": getattr(response, "latency_ms", None),
            },
            indent=2,
        ))
        return 0

    _show_answer(answer, response, hits)
    print(
        "\nNo quality score is printed here on purpose: retrieval metrics need "
        "a labelled\ndataset, not a single question. Run the retrieval "
        "evaluation against\nevaluation/datasets/retrieval_eval.jsonl for "
        "Precision@K, Recall@K, MRR and NDCG@K."
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="rag_demo",
        description="Run the demonstration RAG support bot end to end.",
    )
    parser.add_argument("--query", default=_QUESTION, help="the question to ask")
    parser.add_argument(
        "--top-k",
        type=int,
        default=None,
        help="chunks to retrieve (default: the configured default_top_k)",
    )
    parser.add_argument(
        "--json", action="store_true", help="emit the result as JSON on stdout"
    )
    args = parser.parse_args(argv)

    top_k = args.top_k if args.top_k is not None else settings.default_top_k
    print(f"RAGOps RAG demo — model: {settings.ollama_model} at {settings.ollama_base_url}")
    return asyncio.run(_run(args.query, top_k, args.json))


if __name__ == "__main__":
    raise SystemExit(main())